#!/usr/bin/env node
/** Materialize unmodified original frozen checkpoint weights into production
 * assets. Only intended to run with verified GitHub Actions artifacts.
 * No training or model rewriting occurs.
 */
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {validateComparisonModel} from '../src/architecture-comparison.js';
import {validatePV2Model} from '../src/pv2-ai.js';
const argv=process.argv.slice(2),args={};
for(let i=0;i<argv.length;i+=2){
  if(!['--attention','--gnn','--legacy'].includes(argv[i])||!argv[i+1])
    throw Error('Usage: --attention PATH --gnn PATH --legacy PATH');
  args[argv[i].slice(2)]=argv[i+1];
}
const expected=['attention','gnn','legacy'];
if(!expected.every(k=>args[k]))throw Error('Missing model input');
const artifacts=Object.fromEntries(expected.map(k=>[k,readFileSync(args[k],'utf8')]));
const models=Object.fromEntries(expected.map(k=>[k,JSON.parse(artifacts[k])]));
for(const [key,kind] of [['attention','attn64'],['gnn','gnn64']]){
  const m=validateComparisonModel(models[key]);
  if(m.kind!==kind||m.architecture!=='tgo-comparison-v1'||
     m.metadata.games!==50000||m.metadata.iterations!==6250||
     m.metadata.features!==10||m.metadata.phaseFeature!==false||
     m.metadata.valueOutput!=='independent'||m.metadata.seed!==20261103||
     m.version!==`comparison-${kind}-g50000-seed20261103`)
    throw Error('Not the original validated 50000-game '+kind+' candidate');
}
const old=validatePV2Model(models.legacy);
if(old.architecture!=='hex-group-pv-16-v2'||old.metadata.games!==20000||
   old.metadata.learningRate!==.001||old.metadata.seed!==20261107||
   old.metadata.passInLegalActions!==true||
   !String(old.metadata.initializedFrom).includes('model-102400.json'))
  throw Error('Not the original verified 122400-game pass-aware PV2 candidate');
const payload={
 'elite-attn64-50000':models.attention,
 'elite-gnn64-50000':models.gnn,
 'elite-pv2-122400':models.legacy
};
const provenance={
  generatedFrom:'Original GitHub Actions artifacts, without training/weight modifications',
  models:{
    'elite-attn64-50000':{run:41672945203,artifact:'architecture-milestone-6250-attn64',sha256:createHash('sha256').update(artifacts.attention).digest('hex')},
    'elite-gnn64-50000':{run:41672945203,artifact:'architecture-milestone-6250-gnn64',sha256:createHash('sha256').update(artifacts.gnn).digest('hex')},
    'elite-pv2-122400':{run:41487742023,artifact:'pass-20k-lr001',sha256:createHash('sha256').update(artifacts.legacy).digest('hex')}
  }
};
writeFileSync('src/elite-model-data.js','// Frozen original checkpoint weights. Generated by scripts/generate-elite-assets.mjs.\nexport const ELITE_MODELS='+JSON.stringify(payload)+';\n');
writeFileSync('src/elite-model-provenance.json',JSON.stringify(provenance,null,2)+'\n');
console.log(JSON.stringify({ids:Object.keys(payload),sizes:Object.fromEntries(expected.map(k=>[k,artifacts[k].length])),provenance},null,2));
